package pelemenguin.classjs.content;

import org.objectweb.asm.MethodVisitor;
import org.objectweb.asm.Opcodes;

import dev.latvian.mods.kubejs.typings.Info;
import pelemenguin.util.DescriptorUtils;

public class MethodCreator {

    private ClassCreator parent;

    private int access = 0;
    private String name;
    private String descriptor;
    
    public MethodCreator(ClassCreator parent, String name, String[] parameterTypes, String returnType) {
        this.parent = parent;
        this.name = name;
        this.descriptor = DescriptorUtils.toMethodDescriptor(parameterTypes, returnType);
    }

    @Info(
        """
        Remove `public`, `private`, and `protected` modifiers from this method.
        Such a method can only be accessed from classes in the same package.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toDefault() {
        this.access &= ~(Opcodes.ACC_PUBLIC | Opcodes.ACC_PRIVATE | Opcodes.ACC_PROTECTED);
        return this;
    }

    @Info(
        """
        Set the method to `public`.
        A *public* method can be accessed from any other class.

        **Note:** Interface methods *must* set this flag.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toPublic() {
        this.toDefault();
        this.access |= Opcodes.ACC_PUBLIC;
        return this;
    }

    @Info(
        """
        Set the method to `private`.
        A *private* method can only be accessed from within the same class.

        **Note:** This flag *cannot* be set together with `abstract` flag.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toPrivate() {
        this.toDefault();
        this.access |= Opcodes.ACC_PRIVATE;
        return this;
    }

    @Info(
        """
        Set the method to `protected`.
        A *protected* method can be accessed from classes in the same package and subclasses.

        **Note:** Interface methods *cannot* set this flag.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toProtected() {
        this.toDefault();
        this.access |= Opcodes.ACC_PROTECTED;
        return this;
    }

    @Info(
        """
        Set the method to `static`.
        A *static* method belongs to the class rather than an instance of the class.

        **Note:** This flag *cannot* be set together with `abstract` flag.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toStatic() {
        this.access |= Opcodes.ACC_STATIC;
        return this;
    }

    @Info(
        """
        Remove the `static` modifier from this method.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator notStatic() {
        this.access &= ~Opcodes.ACC_STATIC;
        return this;
    }

    @Info(
        """
        Set the method to `final`.
        A *final* method cannot be overridden by subclasses.

        **Note:** Interface methods *cannot* set this flag.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toFinal() {
        this.access |= Opcodes.ACC_FINAL;
        return this;
    }

    @Info(
        """
        Remove the `final` modifier from this method.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator notFinal() {
        this.access &= ~Opcodes.ACC_FINAL;
        return this;
    }

    @Info(
        """
        Set the method to `synchronized`.
        A *synchronized* method can only be accessed by one thread at a time.

        **Note:** Interface methods *cannot* set this flag.
            This flag *cannot* be set together with `abstract` flag.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toSynchronized() {
        this.access |= Opcodes.ACC_SYNCHRONIZED;
        return this;
    }

    @Info(
        """
        Remove the `synchronized` modifier from this method.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator notSynchronized() {
        this.access &= ~Opcodes.ACC_SYNCHRONIZED;
        return this;
    }

    @Info(
        """
        Set the method to be a `bridge` method.
        A *bridge* method is a synthetic method that is generated by the compiler to handle type erasure in generics.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toBridge() {
        this.access |= Opcodes.ACC_BRIDGE;
        return this;
    }

    @Info(
        """
        Remove the `bridge` modifier from this method.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator notBridge() {
        this.access &= ~Opcodes.ACC_BRIDGE;
        return this;
    }

    @Info(
        """
        Set the method to be a `varargs` method.
        A *varargs* method can accept a variable number of arguments.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toVarargs() {
        this.access |= Opcodes.ACC_VARARGS;
        return this;
    }

    @Info(
        """
        Remove the `varargs` modifier from this method.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator notVarargs() {
        this.access &= ~Opcodes.ACC_VARARGS;
        return this;
    }

    @Info(
        """
        @deprecated You cannot actually creates a `native` method as it requires native code implementation.

        Set the method to be a `native` method.
        A *native* method is implemented in native code using JNI.

        **Note:** Interface methods *cannot* set this flag.
            This flag *cannot* be set together with `abstract` flag.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toNative() {
        this.access |= Opcodes.ACC_NATIVE;
        return this;
    }

    @Info(
        """
        @deprecated You cannot actually creates a `native` method as it requires native code implementation.

        Remove the `native` modifier from this method.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator notNative() {
        this.access &= ~Opcodes.ACC_NATIVE;
        return this;
    }

    @Info(
        """
        Set the method to be an `abstract` method.
        An *abstract* method is a method that is declared without an implementation.

        **Note:** Interface methods *must* set this flag.
            This flag *cannot* be set together with `private`, `static`, `final`, `synchronized`, or `native` flags.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toAbstract() {
        this.access |= Opcodes.ACC_ABSTRACT;
        return this;
    }

    @Info(
        """
        Remove the `abstract` modifier from this method.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator notAbstract() {
        this.access &= ~Opcodes.ACC_ABSTRACT;
        return this;
    }

    @Info(
        """
        @deprecated This flag is unused in class file version 61 (Java 17) or above.

        Set the method to be a `strictfp` method.
        A *strictfp* method is a method that adheres to strict floating-point calculations.

        **Note:** This flag *cannot* be set together with `abstract` flag.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toStrictfp() {
        this.access |= Opcodes.ACC_STRICT;
        return this;
    }

    @Info(
        """
        @deprecated This flag is unused in class file version 61 (Java 17) or above.

        Remove the `strictfp` modifier from this method.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator notStrictfp() {
        this.access &= ~Opcodes.ACC_STRICT;
        return this;
    }

    @Info(
        """
        Set the method to be a `synthetic` method.
        A *synthetic* method is a method that is generated by the compiler and does not appear in the source code.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator toSynthetic() {
        this.access |= Opcodes.ACC_SYNTHETIC;
        return this;
    }

    @Info(
        """
        Remove the `synthetic` modifier from this method.

        @returns This `MethodCreator` instance.
        """
    )
    public MethodCreator notSynthetic() {
        this.access &= ~Opcodes.ACC_SYNTHETIC;
        return this;
    }

    @Info(
        """
        Begin byte code building.

        If you want to create *abstract* methods, use {@linkcode noCode}.

        @returns A `MethodCodeBuilder` for byte code building.  
            **Note:** After the `build()` method of the `MethodCodeBuilder` is called,
            The parent `ClassCreator` is returned directly.
            That means, once you have called this `code()` method, you should no longer access this `MethodCreator` again.
            Access modifier and other properties of this method should be set before calling this method.
        """
    )
    public MethodCodeBuidler code() {
        return new MethodCodeBuidler(this);
    }

    @Info(
        """
        Create a method without any code.
        This is used when creating abstract methods.

        **Note:** After calling this method, the parent `ClassCreator` is returned directly.
            That means, once you have called this `noCode()` method, you should no longer access this `MethodCreator` again.
            Access modifier and other properties of this method should be set before calling this method.

        @returns The parent `ClassCreator`.
        """
    )
    public ClassCreator noCode() {
        MethodVisitor mv = this.parent.classWriter.visitMethod(this.access, this.name, this.descriptor, null, null);
        mv.visitEnd();
        return this.parent;
    }

    public static class MethodCodeBuidler {

        private MethodCreator parent;

        private MethodVisitor methodVisitor;

        public MethodCodeBuidler(MethodCreator parent) {
            this.parent = parent;
            this.methodVisitor = this.parent.parent.classWriter.visitMethod(this.parent.access, this.parent.name, this.parent.descriptor, null, null);
            this.methodVisitor.visitCode();
        }

        @Info(
            """
            Add a `return` instruction to the method.

            The `return` instruction is used to return from a method that has a `void` return type.
            Before `return`, the operand stack must be ***empty***.

            **Operand Stack:**

            {}  
            → {}

            @returns This `MethodCodeBuilder` instance.
            """
        )
        public MethodCodeBuidler returnVoid() {
            this.methodVisitor.visitInsn(Opcodes.RETURN);
            return this;
        }

        @Info(
            """
            Ends the method creation and returns to the parent `ClassCreator`.

            **Note:** Do not try to add any codes after this method.
            They may cause undefined behaviors.

            @returns The parent `ClassCreator`.  
                **Note**: The returned is ***NOT*** the parent `MethodCreator`, but the `ClassCreator`.
            """
        )
        public ClassCreator build() {
            methodVisitor.visitMaxs(0, 0);
            methodVisitor.visitEnd();
            return this.parent.parent;
        }

    }

}
